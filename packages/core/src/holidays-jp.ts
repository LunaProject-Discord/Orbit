export type Holiday = {
  /** YYYY-MM-DD。 */
  date: string;
  name: string;
};

const pad = (value: number) => String(value).padStart(2, "0");

function dateOf(year: number, month: number, day: number): string {
  return `${year}-${pad(month)}-${pad(day)}`;
}

/** その月の n 回目の月曜日。 */
function nthMonday(year: number, month: number, n: number): string {
  const first = Temporal.PlainDate.from({ year, month, day: 1 });
  const offset = (8 - first.dayOfWeek) % 7;
  return first.add({ days: offset + (n - 1) * 7 }).toString();
}

/** 春分日・秋分日の近似式 (1980〜2099 年で使えるもの)。 */
function equinoxDay(year: number, base: number): number {
  const elapsed = year - 1980;
  return Math.floor(base + 0.242194 * elapsed - Math.floor(elapsed / 4));
}

/** 今の祝日法の決まりで、その年の祝日を計算する (振替休日と国民の休日を含む)。 */
export function computeHolidays(year: number): Holiday[] {
  const named = new Map<string, string>([
    [dateOf(year, 1, 1), "元日"],
    [nthMonday(year, 1, 2), "成人の日"],
    [dateOf(year, 2, 11), "建国記念の日"],
    [dateOf(year, 2, 23), "天皇誕生日"],
    [dateOf(year, 3, equinoxDay(year, 20.8431)), "春分の日"],
    [dateOf(year, 4, 29), "昭和の日"],
    [dateOf(year, 5, 3), "憲法記念日"],
    [dateOf(year, 5, 4), "みどりの日"],
    [dateOf(year, 5, 5), "こどもの日"],
    [nthMonday(year, 7, 3), "海の日"],
    [dateOf(year, 8, 11), "山の日"],
    [nthMonday(year, 9, 3), "敬老の日"],
    [dateOf(year, 9, equinoxDay(year, 23.2488)), "秋分の日"],
    [nthMonday(year, 10, 2), "スポーツの日"],
    [dateOf(year, 11, 3), "文化の日"],
    [dateOf(year, 11, 23), "勤労感謝の日"],
  ]);
  const result = new Map(named);
  // 振替休日: 祝日が日曜日なら、その後の最初の祝日でない日を休日にする。
  for (const date of named.keys()) {
    let day = Temporal.PlainDate.from(date);
    if (day.dayOfWeek !== 7) continue;
    do {
      day = day.add({ days: 1 });
    } while (result.has(day.toString()));
    result.set(day.toString(), "休日");
  }
  // 国民の休日: 前日と翌日が祝日の平日 (日曜日でない日) を休日にする。
  for (const date of named.keys()) {
    const between = Temporal.PlainDate.from(date).add({ days: 1 });
    const after = between.add({ days: 1 }).toString();
    if (
      named.has(after) &&
      !result.has(between.toString()) &&
      between.dayOfWeek !== 7
    ) {
      result.set(between.toString(), "休日");
    }
  }
  return [...result]
    .map(([day, name]) => ({ date: day, name }))
    .sort((a, b) => a.date.localeCompare(b.date));
}

/** fromYear から toYear まで (両端を含む) の祝日。一覧のある年は一覧、無い年は計算。 */
export function japaneseHolidays(fromYear: number, toYear: number): Holiday[] {
  const result: Holiday[] = [];
  for (const [date, name] of HOLIDAY_TABLE) {
    const year = Number(date.slice(0, 4));
    if (year >= fromYear && year <= toYear) result.push({ date, name });
  }
  for (
    let year = Math.max(fromYear, TABLE_LAST_YEAR + 1);
    year <= toYear;
    year++
  ) {
    result.push(...computeHolidays(year));
  }
  return result;
}

/** 祝日のカレンダーに入れる年の範囲 (一覧の最初の年から、今年の 10 年後まで)。 */
export function holidayYears(today: string): { from: number; to: number } {
  return { from: 2000, to: Number(today.slice(0, 4)) + 10 };
}

/** 祝日のカレンダーの予定の UID のドメイン。 */
const HOLIDAY_UID_SUFFIX = "@holidays.orbit.lunaproject.jp";

/**
 * 祝日のカレンダーに入れる予定 (終日、空き時間として扱う)。
 * 形は iCalendar を読んだ予定 (ParsedEvent) と同じ。
 */
export function holidayEvents(today: string) {
  const { from, to } = holidayYears(today);
  return japaneseHolidays(from, to).map(({ date, name }) => {
    const next = Temporal.PlainDate.from(date).add({ days: 1 }).toString();
    return {
      uid: `${date}${HOLIDAY_UID_SUFFIX}`,
      recurrenceId: null,
      summary: name,
      location: null,
      description: null,
      status: "confirmed" as const,
      busy: false,
      allDay: true,
      startAt: null,
      endAt: null,
      startDate: date,
      endDate: next,
      startTimeZone: null,
      endTimeZone: null,
      rrule: null,
      rdates: null,
      exdates: null,
      organizer: null,
      attendees: [],
      sequence: 0,
      conferenceUrl: null,
      remoteUpdatedAt: null,
      reminders: [],
      raw: `${date} ${name}`,
    };
  });
}
